#!/usr/bin/env python3
"""Draw the 19 November 2026 world-news infographic (1024x1024 PNG).

The image is drawn with PIL, not generated by an image model, so every
letter is crisp and nothing can come out garbled. It shows six verified
stories from Thursday 19 November 2026, with the date named in the title.

Run:  python3 generate_image.py            (writes entry.png beside this file)
      python3 generate_image.py out.png    (writes to the given path)
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W, H = 1024, 1024

FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
BOLD = str(FONT_DIR / "DejaVuSans-Bold.ttf")
REGULAR = str(FONT_DIR / "DejaVuSans.ttf")

# Palette: paper background, navy header, one accent per story.
PAPER = (248, 246, 241)
NAVY = (14, 42, 71)
NAVY_LIGHT = (24, 58, 92)
GOLD = (232, 184, 75)
INK = (18, 24, 32)
GREY = (74, 82, 94)
CARD = (255, 255, 255)
CARD_EDGE = (224, 220, 212)
FOOT_GREY = (120, 126, 134)

STORIES = [
    (
        "GEOPOLITICS",
        (31, 93, 140),
        "TRUMP, XI AND PUTIN MEET",
        "Trilateral talks in Shenzhen at the APEC summit.",
    ),
    (
        "MIDDLE EAST",
        (178, 58, 44),
        "US AND IRAN EXCHANGE FIRE",
        "US strikes a missile site on Qeshm Island; Iran hits US sites in Bahrain and Kuwait.",
    ),
    (
        "EUROPE",
        (94, 68, 148),
        "CRIMEAN BRIDGE HIT AGAIN",
        "Third attack this week, Russian officials say.",
    ),
    (
        "TECH",
        (24, 122, 88),
        "ANTHROPIC'S $1.4TN DEBUT",
        "Claude-maker raises $81.3bn in the biggest IPO of all time.",
    ),
    (
        "JUSTICE",
        (146, 104, 24),
        "MYANMAR GENOCIDE VERDICT",
        "UN court rules on Rohingya massacres in a historic verdict.",
    ),
    (
        "SCIENCE",
        (18, 110, 138),
        "VOYAGER 1: ONE LIGHT-DAY",
        "NASA probe reaches the milestone 50 years after launch.",
    ),
]


def font(path, size):
    return ImageFont.truetype(path, size)


def wrap(draw, text, fnt, max_width):
    """Split text into lines that fit max_width pixels."""
    lines, line = [], ""
    for word in text.split(" "):
        trial = f"{line} {word}".strip()
        if draw.textlength(trial, font=fnt) <= max_width:
            line = trial
        else:
            if line:
                lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines


def draw_card(draw, x, y, w, h, index, tag, accent, headline, summary):
    draw.rounded_rectangle([x, y, x + w, y + h], radius=14, fill=CARD,
                           outline=CARD_EDGE, width=1)
    # Left accent bar.
    draw.rounded_rectangle([x, y, x + 10, y + h], radius=5, fill=accent)
    pad = 26
    cx = x + pad
    # Measure the content block first so it can sit centred in the card.
    head_font = font(BOLD, 27)
    sum_font = font(REGULAR, 20)
    text_w = w - 2 * pad
    head_lines = wrap(draw, headline, head_font, text_w)
    sum_lines = wrap(draw, summary, sum_font, text_w)
    badge_h = 38
    gap1, gap2 = 16, 10
    content_h = badge_h + gap1 + len(head_lines) * 34 + gap2 + len(sum_lines) * 27
    cy = y + (h - content_h) // 2
    # Number badge.
    badge_r = 19
    draw.ellipse([cx, cy, cx + 2 * badge_r, cy + 2 * badge_r], fill=accent)
    num = font(BOLD, 20)
    t = str(index + 1)
    tw = draw.textlength(t, font=num)
    draw.text((cx + badge_r - tw / 2, cy + badge_r - 13), t,
              font=num, fill=(255, 255, 255))
    # Category tag.
    tag_font = font(BOLD, 15)
    draw.text((cx + 2 * badge_r + 12, cy + 9), tag, font=tag_font, fill=accent)
    # Headline.
    hy = cy + badge_h + gap1
    for line in head_lines:
        draw.text((cx, hy), line, font=head_font, fill=INK)
        hy += 34
    # Summary.
    sy = hy + gap2
    for line in sum_lines:
        draw.text((cx, sy), line, font=sum_font, fill=GREY)
        sy += 27


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent / "entry.png"
    img = Image.new("RGB", (W, H), PAPER)
    draw = ImageDraw.Draw(img)

    # Header band.
    draw.rectangle([0, 0, W, 168], fill=NAVY)
    draw.rectangle([0, 168, W, 172], fill=GOLD)
    title_font = font(BOLD, 62)
    title = "19 NOVEMBER 2026"
    tw = draw.textlength(title, font=title_font)
    draw.text(((W - tw) / 2, 30), title, font=title_font, fill=(255, 255, 255))
    sub_font = font(BOLD, 26)
    sub = "WORLD NEWS IN ONE IMAGE  ·  THURSDAY"
    sw = draw.textlength(sub, font=sub_font)
    draw.text(((W - sw) / 2, 108), sub, font=sub_font, fill=GOLD)

    # Story grid: 2 columns x 3 rows.
    margin, gutter = 36, 24
    card_w = (W - 2 * margin - gutter) // 2
    card_h = 243
    top = 192
    row_gap = 20
    for i, (tag, accent, headline, summary) in enumerate(STORIES):
        row, col = divmod(i, 2)
        x = margin + col * (card_w + gutter)
        y = top + row * (card_h + row_gap)
        draw_card(draw, x, y, card_w, card_h, i, tag, accent, headline, summary)

    # Footer.
    foot_font = font(REGULAR, 15)
    foot = "19 November 2026  ·  Sources: AP, Reuters, BBC, Bloomberg, NASA"
    fw = draw.textlength(foot, font=foot_font)
    draw.text(((W - fw) / 2, 978), foot, font=foot_font, fill=FOOT_GREY)

    img.save(out, format="PNG")
    print(f"wrote {out} ({out.stat().st_size} bytes, {W}x{H})")


if __name__ == "__main__":
    main()
